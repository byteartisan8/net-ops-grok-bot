#!/usr/bin/env python3
"""Resolve contract/oids.yaml from the pinned MIB files in contract/mibs/ (pysmi, offline).

    uv run python tools/gen_oids.py            # (re)write contract/oids.yaml
    uv run python tools/gen_oids.py --check    # exit 1 if contract/oids.yaml differs from a fresh resolution

Only contract/mibs/ is read: no network sources, no pre-compiled or bundled MIBs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from importlib.metadata import version
from pathlib import Path
from typing import Any

import yaml
from pysmi.codegen import JsonCodeGen
from pysmi.compiler import MibCompiler
from pysmi.parser import SmiV1CompatParser
from pysmi.reader import FileReader
from pysmi.writer import CallbackWriter

REPO_ROOT = Path(__file__).resolve().parents[1]
MIB_DIR = REPO_ROOT / "contract" / "mibs"
OIDS_YAML = REPO_ROOT / "contract" / "oids.yaml"

# Objects and notifications of contract section 8 (plus the full system group, ifNumber and snmpTrapOID).
# Tables, rows and index columns they need, and every notification varbind object, are added automatically.
REQUESTED_OBJECTS: dict[str, list[str]] = {
    "SNMPv2-MIB": [
        "system", "sysDescr", "sysObjectID", "sysUpTime", "sysContact", "sysName", "sysLocation", "sysServices",
        "snmpTrapOID",
    ],
    "IF-MIB": [
        "ifNumber", "ifTable", "ifEntry", "ifIndex", "ifDescr", "ifType", "ifMtu", "ifAdminStatus", "ifOperStatus",
        "ifXTable", "ifXEntry", "ifName", "ifAlias",
    ],
    "CISCO-IETF-PW-MIB": [
        "cpwVcTable", "cpwVcEntry", "cpwVcIndex", "cpwVcType", "cpwVcPsnType", "cpwVcPeerAddrType", "cpwVcPeerAddr",
        "cpwVcID", "cpwVcLocalIfMtu", "cpwVcRemoteIfMtu", "cpwVcRemoteIfString", "cpwVcName", "cpwVcDescr",
        "cpwVcAdminStatus", "cpwVcOperStatus", "cpwVcInboundOperStatus", "cpwVcOutboundOperStatus", "cpwVcUpTime",
    ],
}  # fmt: skip
REQUESTED_NOTIFICATIONS: dict[str, list[str]] = {
    "SNMPv2-MIB": ["coldStart"],
    "IF-MIB": ["linkDown", "linkUp"],
    "CISCO-IETF-PW-MIB": ["cpwVcDown", "cpwVcUp"],
    "CISCO-CONFIG-MAN-MIB": ["ciscoConfigManEvent"],
}

# SMIv2 base types: resolution of textual conventions stops here (SNMPv2-SMI defines the application
# types as INTEGER/OCTET STRING refinements, but they are distinct types on the wire).
BASE_TYPES = frozenset({
    "INTEGER", "Integer32", "Unsigned32", "Gauge32", "Counter32", "Counter64", "TimeTicks",
    "OCTET STRING", "OBJECT IDENTIFIER", "IpAddress", "Opaque", "Bits", "BITS",
})  # fmt: skip
KNOWN_CONSTRAINTS = frozenset({"enumeration", "range", "size"})

HEADER = """\
# GENERATED by tools/gen_oids.py from the pinned MIB files in contract/mibs/ (pysmi) - DO NOT EDIT.
# Regenerate with `make contract`; tests/test_oids.py re-resolves the MIBs and fails if this file differs.
#
# objects        Every object of contract section 8, the tables/rows/index columns they need, and every
#                object referenced by a notification below. Scalars carry their instance OID (oid.0); the
#                instance of a column is <oid>.<index values of its row> (netsim_common.oids.OidRegistry.instance).
# notifications  `objects` is the OBJECTS clause in order. A v2c trap carries sysUpTime.0 and snmpTrapOID.0
#                first, then these varbinds (RFC 3416 section 4.2.6). For cpwVcDown/cpwVcUp the two
#                cpwVcOperStatus varbinds bound the range of affected cpwVcIndex values (see description).
# syntax         `type` as written in the MIB, `base` = SMI base type after resolving textual conventions
#                (pysnmp class: netsim_common.oids.PYSNMP_TYPE_BY_BASE), `enum` label -> value.
"""


def compile_mibs(mib_dir: Path = MIB_DIR) -> dict[str, dict[str, Any]]:
    """Compile every pinned module to pysmi's JSON representation (in memory)."""
    modules = sorted({p.name.split(".")[0] for p in mib_dir.iterdir() if p.suffix in (".my", ".txt")})
    out: dict[str, dict[str, Any]] = {}

    def store(name: str, data: str, _ctx: Any) -> None:
        out[name] = json.loads(data)

    compiler = MibCompiler(SmiV1CompatParser(tempdir=""), JsonCodeGen(), CallbackWriter(store))
    compiler.add_sources(FileReader(str(mib_dir), recursive=False))
    status = compiler.compile(*modules, genTexts=True, rebuild=True, ignoreErrors=False)
    failed = {m: str(s) for m, s in status.items() if str(s) != "compiled"}
    if failed or set(out) != set(modules):
        raise RuntimeError(f"MIB compilation failed: {failed or sorted(set(modules) - set(out))}")
    return out


def _oid_key(oid: str) -> tuple[int, ...]:
    return tuple(int(x) for x in oid.split("."))


def _ranges(items: list[dict[str, Any]]) -> str:
    return " | ".join(str(r["min"]) if r["min"] == r["max"] else f"{r['min']}..{r['max']}" for r in items)


def _text(value: str) -> str:
    return " ".join(value.split())


class Resolver:
    def __init__(self, compiled: dict[str, dict[str, Any]]):
        self.compiled = compiled
        self.by_oid: dict[str, tuple[str, str]] = {}
        for module, symbols in compiled.items():
            for name, node in symbols.items():
                if isinstance(node, dict) and "oid" in node:
                    self.by_oid.setdefault(node["oid"], (module, name))

    def node(self, module: str, name: str) -> dict[str, Any]:
        try:
            return self.compiled[module][name]
        except KeyError:
            raise KeyError(f"{module}::{name} not found in the pinned MIBs") from None

    def defining_module(self, module: str, name: str) -> str:
        if name in self.compiled[module] and name != "imports":
            return module
        for source, symbols in self.compiled[module].get("imports", {}).items():
            if source != "class" and name in symbols:
                return self.defining_module(source, name)
        raise KeyError(f"cannot resolve type {name!r} used in {module}")

    def syntax(self, module: str, syntax: dict[str, Any]) -> dict[str, Any]:
        written = syntax["type"]
        constraints = dict(syntax.get("constraints") or {})
        tc_module: str | None = None
        display_hint: str | None = None
        current, where = written, module
        while current not in BASE_TYPES:
            defined_in = self.defining_module(where, current)
            node = self.node(defined_in, current)
            if node.get("class") not in ("textualconvention", "type"):
                raise ValueError(f"{defined_in}::{current} is a {node.get('class')}, not a type")
            tc_module = tc_module or defined_in
            display_hint = display_hint or node.get("displayhint")
            inner = node["type"]
            for key, value in (inner.get("constraints") or {}).items():
                constraints.setdefault(key, value)  # the most specific (outermost) constraint wins
            current, where = inner["type"], defined_in
        if unknown := set(constraints) - KNOWN_CONSTRAINTS:
            raise ValueError(f"unsupported constraint(s) {unknown} in {module} {written}")
        out: dict[str, Any] = {"type": written, "base": current}
        if tc_module:
            out["tc_module"] = tc_module
        if display_hint:
            out["display_hint"] = display_hint
        if "enumeration" in constraints:
            out["enum"] = dict(sorted(constraints["enumeration"].items(), key=lambda kv: kv[1]))
        if "range" in constraints:
            out["range"] = _ranges(constraints["range"])
        if "size" in constraints:
            out["size"] = _ranges(constraints["size"])
        return out

    def parent(self, oid: str) -> tuple[str, str]:
        parent_oid = oid.rsplit(".", 1)[0]
        if parent_oid not in self.by_oid:
            raise KeyError(f"no MIB node for parent OID {parent_oid}")
        return self.by_oid[parent_oid]

    def row_index(self, module: str, row: str) -> tuple[list[tuple[str, str]], str | None]:
        node = self.node(module, row)
        if "augmention" in node:
            aug = node["augmention"]
            index, _ = self.row_index(aug["module"], aug["object"])
            return index, aug["object"]
        return [(i["module"], i["object"]) for i in node.get("indices", [])], None


def build(mib_dir: Path = MIB_DIR) -> dict[str, Any]:
    """Resolve the registry (the data written to contract/oids.yaml)."""
    compiled = compile_mibs(mib_dir)
    res = Resolver(compiled)

    wanted: dict[str, str] = {}  # object name -> module
    pending = [(m, n) for m, names in REQUESTED_OBJECTS.items() for n in names]
    for module, names in REQUESTED_NOTIFICATIONS.items():
        for name in names:
            pending += [(o["module"], o["object"]) for o in res.node(module, name).get("objects", [])]
    while pending:
        module, name = pending.pop()
        if name in wanted:
            if wanted[name] != module:
                raise ValueError(f"object name {name} defined in both {wanted[name]} and {module}")
            continue
        wanted[name] = module
        node = res.node(module, name)
        kind = node.get("nodetype")
        if kind == "column":
            pending.append(res.parent(node["oid"]))
        elif kind == "row":
            pending.append(res.parent(node["oid"]))
            index, augments = res.row_index(module, name)
            pending += index
            if augments:
                pending.append((module, augments))

    objects: dict[str, Any] = {}
    for name, module in sorted(wanted.items(), key=lambda kv: _oid_key(res.node(kv[1], kv[0])["oid"])):
        node = res.node(module, name)
        kind = node.get("nodetype") if node["class"] == "objecttype" else "node"
        entry: dict[str, Any] = {"module": module, "oid": node["oid"], "kind": kind}
        if kind == "scalar":
            entry["instance"] = f"{node['oid']}.0"
        if kind == "column":
            row_module, row = res.parent(node["oid"])
            entry["table"] = res.parent(res.node(row_module, row)["oid"])[1]
            entry["row"] = row
        if kind == "row":
            entry["table"] = res.parent(node["oid"])[1]
            index, augments = res.row_index(module, name)
            if augments:
                entry["augments"] = augments
            entry["index"] = [i for _, i in index]
        if "maxaccess" in node:
            entry["access"] = node["maxaccess"]
        if node.get("syntax"):
            entry["syntax"] = res.syntax(module, node["syntax"])
        objects[name] = entry

    notifications: dict[str, Any] = {}
    flat = [(m, n) for m, names in REQUESTED_NOTIFICATIONS.items() for n in names]
    for module, name in sorted(flat, key=lambda mn: _oid_key(res.node(*mn)["oid"])):
        node = res.node(module, name)
        varbinds = []
        for ref in node.get("objects", []):
            obj = res.node(ref["module"], ref["object"])
            index: list[str] = []
            if obj.get("nodetype") == "column":
                row_module, row = res.parent(obj["oid"])
                index = [i for _, i in res.row_index(row_module, row)[0]]
            varbinds.append({"name": ref["object"], "module": ref["module"], "oid": obj["oid"], "index": index})
        notifications[name] = {
            "module": module,
            "oid": node["oid"],
            "objects": varbinds,
            "description": _text(node.get("description", "")),
        }

    mibs: dict[str, Any] = {}
    for module in sorted(compiled):
        path = next(p for p in mib_dir.iterdir() if p.name.split(".")[0] == module)
        info: dict[str, Any] = {"file": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        identity = next(
            (v for v in compiled[module].values() if isinstance(v, dict) and v.get("class") == "moduleidentity"), None
        )
        if identity:
            info["identity"] = identity["name"]
            info["oid"] = identity["oid"]
            if identity.get("revisions"):
                info["revision"] = identity["revisions"][0]["revision"]
        mibs[module] = info

    return {
        "generator": {"tool": "tools/gen_oids.py", "pysmi": version("pysmi")},
        "mibs": mibs,
        "objects": objects,
        "notifications": notifications,
    }


def render(data: dict[str, Any]) -> str:
    body = yaml.safe_dump(data, sort_keys=False, default_flow_style=False, width=100, allow_unicode=False)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify only, do not write")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        if not OIDS_YAML.exists() or OIDS_YAML.read_text(encoding="utf-8") != text:
            print("ERROR: contract/oids.yaml is out of date - run `make contract`", file=sys.stderr)
            return 1
        print("OK: contract/oids.yaml matches the pinned MIBs")
        return 0
    if not OIDS_YAML.exists() or OIDS_YAML.read_text(encoding="utf-8") != text:
        OIDS_YAML.write_text(text, encoding="utf-8")
        print(f"wrote {OIDS_YAML.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
