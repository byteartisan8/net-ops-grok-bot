#!/usr/bin/env python3
"""Download the pinned MIB modules into contract/mibs/ and (re)write SOURCES.md.

Every file is fetched from an immutable commit URL and its sha256 is recorded.

    uv run python tools/fetch_mibs.py            # download + write SOURCES.md
    uv run python tools/fetch_mibs.py --check    # verify files on disk against SOURCES.md (offline)
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import urllib.request
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MIB_DIR = REPO_ROOT / "contract" / "mibs"
SOURCES_MD = MIB_DIR / "SOURCES.md"


@dataclass(frozen=True)
class Upstream:
    repo: str  # GitHub owner/name
    tag: str  # human-readable ref (tag or branch at pin time)
    commit: str  # immutable commit SHA used in the download URL
    directory: str  # directory inside the repo
    suffix: str  # upstream file suffix


CISCO = Upstream(
    repo="cisco/cisco-mibs",
    tag="main",
    commit="c9ab98c03ee051de74edda72f6d5c43ee65cad91",
    directory="v2",
    suffix=".my",
)
NET_SNMP = Upstream(
    repo="net-snmp/net-snmp",
    tag="v5.9.5.2",
    commit="319bbd0bb36547992c0e1302fef278c6f49d0c80",
    directory="mibs",
    suffix=".txt",
)

# module name -> upstream. Cisco modules come from Cisco's official repo; IETF/IANA modules
# come from net-snmp (RFC-faithful copies, same family as the snmptrapd used by Zabbix).
MODULES: dict[str, Upstream] = {
    "SNMPv2-SMI": NET_SNMP,
    "SNMPv2-TC": NET_SNMP,
    "SNMPv2-CONF": NET_SNMP,
    "SNMPv2-MIB": NET_SNMP,
    "SNMP-FRAMEWORK-MIB": NET_SNMP,
    "IANAifType-MIB": NET_SNMP,
    "IF-MIB": NET_SNMP,
    "INET-ADDRESS-MIB": NET_SNMP,
    "CISCO-SMI": CISCO,
    "CISCO-TC": CISCO,
    "CISCO-IETF-PW-TC-MIB": CISCO,
    "CISCO-IETF-PW-MIB": CISCO,
    "CISCO-CONFIG-MAN-MIB": CISCO,
}

ROW_RE = re.compile(r"^\| `(?P<file>[^`]+)` \| `(?P<module>[^`]+)` \|.*\| `(?P<sha>[0-9a-f]{64})` \|$")


def file_name(module: str) -> str:
    return module + MODULES[module].suffix


def url_for(module: str) -> str:
    up = MODULES[module]
    return f"https://raw.githubusercontent.com/{up.repo}/{up.commit}/{up.directory}/{file_name(module)}"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def last_updated(path: Path) -> str:
    match = re.search(r'^\s*LAST-UPDATED\s+"(\d+Z)"', path.read_text(encoding="latin-1"), re.MULTILINE)
    return match.group(1) if match else "-"


def download() -> None:
    MIB_DIR.mkdir(parents=True, exist_ok=True)
    for module in MODULES:
        url = url_for(module)
        with urllib.request.urlopen(url, timeout=60) as resp:
            data = resp.read()
        (MIB_DIR / file_name(module)).write_bytes(data)
        print(f"fetched {module:<22} {len(data):>7} bytes  {url}")


def render_sources_md() -> str:
    lines = [
        "# Pinned MIB modules",
        "",
        "Generated by `tools/fetch_mibs.py` - do not edit by hand. Re-run the tool to change a pin;",
        "`uv run python tools/fetch_mibs.py --check` (and the test suite) verify every sha256 below.",
        "",
        "Files are stored under their upstream file names. pysmi (`tools/gen_oids.py`) reads only this",
        "directory - no network or bundled MIBs - to produce `contract/oids.yaml`.",
        "",
        "## Upstreams",
        "",
        "| Upstream | Ref at pin time | Commit | Why |",
        "|---|---|---|---|",
        f"| [{CISCO.repo}](https://github.com/{CISCO.repo}) | `{CISCO.tag}` | `{CISCO.commit}` "
        "| Cisco's official MIB repository (CISCO-* modules) |",
        f"| [{NET_SNMP.repo}](https://github.com/{NET_SNMP.repo}) | tag `{NET_SNMP.tag}` | `{NET_SNMP.commit}` "
        "| RFC-faithful IETF/IANA modules, same family as the net-snmp used by snmptrapd |",
        "",
        "## Files",
        "",
        "| File | Module | LAST-UPDATED | Upstream | Ref | sha256 |",
        "|---|---|---|---|---|---|",
    ]
    for module in MODULES:
        up = MODULES[module]
        path = MIB_DIR / file_name(module)
        lines.append(
            f"| `{file_name(module)}` | `{module}` | `{last_updated(path)}` "
            f"| [{up.repo}/{up.directory}/{file_name(module)}]({url_for(module)}) "
            f"| `{up.tag}` @ `{up.commit[:12]}` | `{sha256(path)}` |"
        )
    lines += [
        "",
        "## Notes",
        "",
        "- `IANAifType-MIB` is the net-snmp v5.9.5.2 snapshot (LAST-UPDATED 2022-08-17). The live IANA registry",
        "  (<https://www.iana.org/assignments/ianaiftype-mib/ianaiftype-mib>) is newer; the lab only uses",
        "  long-standing values (`ethernetCsmacd`, `l2vlan`), so the tag-pinned copy is preferred for reproducibility.",
        "- Cisco's `v2/` directory also ships copies of the IETF modules; their content (comments aside) is",
        "  identical, except that Cisco's `SNMPv2-TC` omits the TEXTUAL-CONVENTION macro text from RFC 2579.",
        "",
    ]
    return "\n".join(lines)


def parse_sources_md(text: str) -> dict[str, tuple[str, str]]:
    """Return {file name: (module, sha256)} from the Files table of SOURCES.md."""
    rows: dict[str, tuple[str, str]] = {}
    for line in text.splitlines():
        match = ROW_RE.match(line)
        if match:
            rows[match["file"]] = (match["module"], match["sha"])
    return rows


def check() -> list[str]:
    """Verify contract/mibs against SOURCES.md; return a list of problems (empty = OK)."""
    problems: list[str] = []
    rows = parse_sources_md(SOURCES_MD.read_text(encoding="utf-8"))
    expected_files = {file_name(m) for m in MODULES}
    if set(rows) != expected_files:
        problems.append(f"SOURCES.md rows {sorted(rows)} != manifest {sorted(expected_files)}")
    on_disk = {p.name for p in MIB_DIR.iterdir() if p.is_file() and p.name != SOURCES_MD.name}
    if on_disk != expected_files:
        problems.append(f"files on disk {sorted(on_disk)} != manifest {sorted(expected_files)}")
    for name, (_module, digest) in sorted(rows.items()):
        path = MIB_DIR / name
        if not path.is_file():
            problems.append(f"missing {name}")
        elif sha256(path) != digest:
            problems.append(f"sha256 mismatch for {name}: {sha256(path)} != {digest}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify files against SOURCES.md, no network")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        if not problems:
            print(f"OK: {len(MODULES)} MIB files match {SOURCES_MD.relative_to(REPO_ROOT)}")
        return 1 if problems else 0
    download()
    SOURCES_MD.write_text(render_sources_md(), encoding="utf-8")
    print(f"wrote {SOURCES_MD.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
