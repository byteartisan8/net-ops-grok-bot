"""The controller's startup datastore (``controller/startup_db``), generated from ``contract/topology.yaml``.

    uv run python controller/startup.py [--check]       # = make controller-config / controller-check

The controller starts from this file every time (``clixon_backend -s startup``, a fresh datastore per start):

* **devices:** one per PE of the topology, by name, at its mgmt IP, through the profile ``netsim-pe`` (NETCONF over SSH
  on port 830 as the PEs' user ``controller``); a device group per region (``north``, ``south``);
* **NACM** (RFC 8341, ``CLICON_NACM_MODE=internal``): reading is allowed, writing is not, and an RPC runs only when a
  rule grants it. The three NOC roles (``noc-engineer``, ``network-engineer``, ``noc-manager``) may read and nothing
  else: no edit, commit, pull, push or connection change. ``lab-api`` may also pull and (re)connect routers;
  ``admin`` (people, ``make controller-shell``) may do everything. ``root`` is the recovery user (the container's
  own connect job; ``CLICON_NACM_CREDENTIALS=exact``, so nobody else can pose as root or as anyone else).

NACM names RPCs, never their arguments: ``show devices <host> check`` and ``diff`` send ``config-pull`` with
``transient=true``, the RPC a real pull sends, so the roles do not get ``config-pull`` and lab-api runs those two
commands as its own user (contract, controller section).
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
OUT = HERE / "startup_db"
HEADER = (
    "<!-- GENERATED by `make controller-config` (controller/startup.py) from contract/topology.yaml - DO NOT EDIT.\n"
    "     The Clixon controller's startup datastore: the PEs it manages and its NACM rules (owner:\n"
    "     10-clixon-controller). Loaded at every start of the controller container. -->\n"
)
CONTROLLER_NS = "http://clicon.org/controller"
NACM_NS = "urn:ietf:params:xml:ns:yang:ietf-netconf-acm"
PROFILE = "netsim-pe"
#: The PEs' NETCONF over SSH (devices/sshd_config): port and the one user that may log in.
DEVICE_PORT = 830
DEVICE_USER = "controller"
#: Seconds to set up a connection (TCP, SSH, hello) and for any other device operation (pull, RPC).
CONNECT_TIMEOUT = 5
DEVICE_TIMEOUT = 30

ROLE_USERS = ("noc-engineer", "network-engineer", "noc-manager")
LAB_API_USER = "lab-api"
ADMIN_USER = "admin"
#: RPCs every CLI user needs to read: the datastore (get-config), config plus state such as the connection table
#: (get), the CLI's own start-up (clixon-cache: the autocli specs of the routers' YANG, read; its only other operation
#: clears caches; nacm-autocli-filter-get: what NACM hides from completion; create-subscription: the controller CLI
#: follows its transactions' notifications), config-path-info and translate-format (how the CLI resolves a path into a
#: router's config and prints it, for `show configuration devices device <pe> config <subtree>`) and leaving the
#: session cleanly (close-session is always allowed by RFC 8341, listed for clarity).
READ_RPCS = (
    "get",
    "get-config",
    "clixon-cache",
    "nacm-autocli-filter-get",
    "create-subscription",
    "config-path-info",
    "translate-format",
    "close-session",
)
#: What lab-api adds: pull a router's config (a transient pull = check/diff), (re)connect routers, the diff the CLI
#: asks for after a transient pull, and what the CLI does around each such transaction: fetch its per-device result
#: (device-rpc-result) and abort it when that fails (transaction-error).
LAB_API_RPCS = ("config-pull", "connection-change", "datastore-diff", "device-rpc-result", "transaction-error")
#: Never for the roles, named so the rule shows up in `show configuration nacm` (exec-default deny covers the rest):
#: edits and commits of the controller's own datastore, pulls, pushes (controller-commit), connection changes,
#: arbitrary device RPCs and templates, locks, session kills.
ROLE_DENIED_RPCS = (
    "edit-config",
    "copy-config",
    "delete-config",
    "commit",
    "discard-changes",
    "validate",
    "lock",
    "unlock",
    "kill-session",
    "config-pull",
    "controller-commit",
    "connection-change",
    "device-rpc",
    "device-template-apply",
)


@dataclass(frozen=True)
class Rule:
    name: str
    action: str
    rpc: str | None = None
    module: str = "*"
    access: str = "*"
    comment: str | None = None


def _rules() -> dict[str, tuple[str, list[Rule]]]:
    """Rule lists by name: (group, rules in order; first match wins)."""
    roles = [Rule(f"deny-{rpc}", "deny", rpc=rpc, access="exec") for rpc in ROLE_DENIED_RPCS]
    roles += [Rule(f"permit-{rpc}", "permit", rpc=rpc, access="exec") for rpc in READ_RPCS]
    roles.append(Rule("hide-nacm", "deny", module="ietf-netconf-acm", access="read"))
    lab_api = [Rule(f"permit-{rpc}", "permit", rpc=rpc, access="exec") for rpc in (*READ_RPCS, *LAB_API_RPCS)]
    lab_api.append(Rule("deny-push", "deny", rpc="controller-commit", access="exec"))
    admin = [Rule("permit-all", "permit")]
    return {"noc-roles": ("noc-roles", roles), "lab-api": ("lab-api", lab_api), "admin": ("admin", admin)}


def _groups() -> dict[str, tuple[str, ...]]:
    return {"noc-roles": ROLE_USERS, "lab-api": (LAB_API_USER,), "admin": (ADMIN_USER,)}


def _el(tag: str, value: object, indent: int) -> str:
    return f"{' ' * indent}<{tag}>{escape(str(value))}</{tag}>"


def render_startup(topology: object | None = None) -> str:
    """The startup datastore XML for ``topology`` (default: ``contract/topology.yaml``)."""
    from netsim_common.topology import load_topology

    topo = topology or load_topology()
    lines = [HEADER.rstrip("\n"), "<config>", f'  <devices xmlns="{CONTROLLER_NS}">']
    lines += [_el("device-timeout", DEVICE_TIMEOUT, 4), _el("connect-timeout", CONNECT_TIMEOUT, 4)]
    for region in topo.regions:  # type: ignore[attr-defined]
        members = [d.hostname for d in topo.devices if topo.region_of(d.hostname) == region.name]  # type: ignore[attr-defined]
        lines += ["    <device-group>", _el("name", region.name.lower(), 6)]
        lines.append(_el("description", f"{region.name} region: {', '.join(members)}", 6))
        lines += [_el("device-name", m, 6) for m in members]
        lines.append("    </device-group>")
    lines += [
        "    <device-profile>",
        _el("name", PROFILE, 6),
        _el("description", "NetSim PE (Clixon 7.9.0): NETCONF over SSH, YANG from the device (RFC 6022)", 6),
        _el("user", DEVICE_USER, 6),
        _el("conn-type", "NETCONF_SSH", 6),
        _el("ssh-stricthostkey", "true", 6),
        _el("port", DEVICE_PORT, 6),
        _el("yang-config", "BIND", 6),
        "    </device-profile>",
    ]
    for d in topo.devices:  # type: ignore[attr-defined]
        region = topo.region_of(d.hostname)  # type: ignore[attr-defined]
        lines += [
            "    <device>",
            _el("name", d.hostname, 6),
            _el("enabled", "true", 6),
            _el("description", f"{d.role.value} at {d.site}" + (f" ({region})" if region else ""), 6),
            _el("device-profile", PROFILE, 6),
            _el("device-type", f"netsim-pe {d.role.value}", 6),
            _el("addr", d.mgmt_ip, 6),
            "    </device>",
        ]
    lines.append("  </devices>")
    lines += [
        f'  <nacm xmlns="{NACM_NS}">',
        _el("enable-nacm", "true", 4),
        _el("read-default", "permit", 4),
        _el("write-default", "deny", 4),
        _el("exec-default", "deny", 4),
        "    <groups>",
    ]
    for name, users in _groups().items():
        lines += ["      <group>", _el("name", name, 8), *(_el("user-name", u, 8) for u in users), "      </group>"]
    lines.append("    </groups>")
    for name, (group, rules) in _rules().items():
        lines += ["    <rule-list>", _el("name", name, 6), _el("group", group, 6)]
        for r in rules:
            lines += ["      <rule>", _el("name", r.name, 8), _el("module-name", r.module, 8)]
            if r.rpc:
                lines.append(_el("rpc-name", r.rpc, 8))
            lines += [_el("access-operations", r.access, 8), _el("action", r.action, 8), "      </rule>"]
        lines.append("    </rule-list>")
    lines += ["  </nacm>", "</config>"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify controller/startup_db is current")
    args = parser.parse_args(argv)
    text = render_startup()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"ERROR: {OUT} is out of date - run `make controller-config`", file=sys.stderr)
            return 1
        print(f"OK: {OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
