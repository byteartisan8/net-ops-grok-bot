"""``netsim-devices``: developer tooling for the devices component (compose rendering, readiness wait).

    netsim-devices render-compose [--check]     # devices/compose.yaml from contract/topology.yaml
    netsim-devices wait [--timeout 60]          # wait until every device is healthy and every PW is up

The compose file is generated so device addresses, ports and identities can never drift from the topology:
one ``core`` (Valkey, keyspace notifications on) plus one ``netsim-pe`` container per device with its mgmt
IP on the external network, host ports ``base + last octet`` on 127.0.0.1, a named volume and the env
contract (``HOSTNAME``, ``MGMT_IP``, ``CORE_URL``, ``TRAP_TARGETS``, ``SNMP_COMMUNITY``, ``SITE``).
:func:`render_compose` also renders the isolated stacks used by the integration tests.
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import sys
import time
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

import yaml

from netsim_common.constants import CORE, ZABBIX_SNMPTRAPS, lab_constants
from netsim_common.paths import repo_root
from netsim_common.topology import Topology, load_topology
from netsim_simd import __version__

IMAGE = f"netsim/netsim-pe:{__version__}"
CORE_IMAGE = "valkey/valkey:8.1.10-alpine3.24"
#: K = keyspace channel, E = keyevent channel, g = DEL/EXPIRE..., $ = string commands, x = expired.
KEYSPACE_EVENTS = "KEg$x"
TRAPSINK_HTTP_PORT = 9162
DEVICE_VOLUME_PATH = "/var/lib/netsim"
#: Public SSH keys shared with the Clixon controller (10-clixon-controller): the controller writes controller.pub, each
#: PE's sshd authorizes it for the NETCONF user ``controller``. Read-only here.
CONTROLLER_KEYS_VOLUME = "controller-keys"
CONTROLLER_KEYS_PATH = "/etc/netsim/keys"
HEADER = """\
# GENERATED by `make devices-compose` (netsim-devices render-compose) from contract/topology.yaml - DO NOT EDIT.
# Owner: 02-device-simulator. `core` (Valkey signaling bus) + one netsim-pe container per device, all on the
# external network labnet (created by `make net`). Device ports bind to 127.0.0.1 only (contract section 4).
# CORE_URL, TRAP_TARGETS and SNMP_COMMUNITY come from the root .env; the defaults match .env.example
# (TRAP_TARGETS set but empty disables traps). The volume controller-keys (read-only here) brings the Clixon
# controller's public key for NETCONF over SSH on :830, which is not published (labnet only).
"""


@dataclass(frozen=True)
class RenderOptions:
    hosts: tuple[str, ...] | None = None
    network: str | None = None
    external_network: bool = True
    subnet: str | None = None
    container_prefix: str = ""
    publish: Literal["topology", "ephemeral"] = "topology"
    trapsink: bool = False
    trap_targets: str | None = None
    build_context: str = ".."
    image: str = IMAGE
    header: str = HEADER


def _env_example_default(name: str) -> str:
    for line in (repo_root() / ".env.example").read_text(encoding="utf-8").splitlines():
        if line.startswith(f"{name}="):
            return line.split("=", 1)[1]
    raise KeyError(f"{name} is not in .env.example")


def _remap(ip: str, subnet: str | None) -> str:
    if subnet is None:
        return ip
    net = ipaddress.IPv4Network(subnet)
    return str(net.network_address + int(ip.rsplit(".", 1)[1]))


def render_compose(topology: Topology | None = None, options: RenderOptions | None = None) -> str:
    topo = topology or load_topology()
    opts = options or RenderOptions()
    lab = lab_constants(topo)
    hosts = opts.hosts or tuple(topo.hostnames)
    network = opts.network or topo.network.name
    core = topo.infra(CORE)
    core_ip = _remap(core.mgmt_ip, opts.subnet)
    core_url = f"redis://{core_ip}:{core.container_port}/0"
    if opts.subnet is None:
        core_env = f"${{CORE_URL:-{lab.core_url}}}"
        traps_env = opts.trap_targets or f"${{TRAP_TARGETS-{_env_example_default('TRAP_TARGETS')}}}"
        community_env = f"${{SNMP_COMMUNITY:-{lab.snmp_community}}}"
    else:
        core_env = core_url
        traps_env = opts.trap_targets if opts.trap_targets is not None else ""
        community_env = lab.snmp_community

    def net(ip: str) -> dict[str, Any]:
        return {network: {"ipv4_address": ip}}

    services: dict[str, Any] = {
        "core": {
            "image": CORE_IMAGE,
            "container_name": f"{opts.container_prefix}core",
            "hostname": "core",
            "command": [
                "valkey-server",
                "--save",
                "",
                "--appendonly",
                "no",
                "--notify-keyspace-events",
                KEYSPACE_EVENTS.replace("$", "$$"),
            ],
            "networks": net(core_ip),
            "healthcheck": {"test": ["CMD", "valkey-cli", "ping"], "interval": "2s", "timeout": "2s", "retries": 15},
            "restart": "unless-stopped",
        }
    }
    volumes: dict[str, Any] = {}
    for host in hosts:
        device = topo.device(host)
        ip = _remap(device.mgmt_ip, opts.subnet)
        service: dict[str, Any] = {
            "image": opts.image,
            "build": {"context": opts.build_context, "dockerfile": "devices/Dockerfile"},
            "container_name": f"{opts.container_prefix}{host}",
            "hostname": host,
            "environment": {
                "HOSTNAME": host,
                "MGMT_IP": ip,
                "SITE": device.site,
                "CORE_URL": core_env,
                "TRAP_TARGETS": traps_env,
                "SNMP_COMMUNITY": community_env,
            },
            "networks": net(ip),
        }
        ports = []
        for kind in ("restconf", "simd", "snmp"):
            scheme = getattr(topo.device_ports, kind)
            if opts.publish == "topology":
                ports.append(f"{topo.host_bind}:{topo.host_port(host, kind)}:{scheme.container}/{scheme.protocol}")
            else:
                ports.append(f"{topo.host_bind}::{scheme.container}/{scheme.protocol}")
        service["ports"] = ports
        volume = f"{host}-data"
        service["volumes"] = [f"{volume}:{DEVICE_VOLUME_PATH}", f"{CONTROLLER_KEYS_VOLUME}:{CONTROLLER_KEYS_PATH}:ro"]
        volumes[volume] = {}
        service["depends_on"] = {"core": {"condition": "service_healthy"}}
        service["healthcheck"] = {
            "interval": "5s",
            "timeout": "4s",
            "retries": 3,
            "start_period": "60s",
            "start_interval": "1s",
        }
        service["stop_grace_period"] = "5s"
        service["restart"] = "unless-stopped"
        services[host] = service
    if opts.trapsink:
        sink_ip = _remap(topo.infra(ZABBIX_SNMPTRAPS).mgmt_ip, opts.subnet)
        services["trapsink"] = {
            "image": opts.image,
            "container_name": f"{opts.container_prefix}trapsink",
            "hostname": "trapsink",
            "entrypoint": ["netsim-trapsink", "--listen", "0.0.0.0:1162", "--http", f"0.0.0.0:{TRAPSINK_HTTP_PORT}"],
            "healthcheck": {"disable": True},
            "networks": net(sink_ip),
            "ports": [f"{topo.host_bind}::{TRAPSINK_HTTP_PORT}/tcp"],
        }
    doc: dict[str, Any] = {"services": services}
    if opts.external_network:
        doc["networks"] = {network: {"external": True}}
    else:
        doc["networks"] = {network: {"ipam": {"config": [{"subnet": opts.subnet or topo.network.subnet}]}}}
    doc["volumes"] = {**volumes, CONTROLLER_KEYS_VOLUME: {}}
    return opts.header + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=120)


def openapi_document() -> dict[str, Any]:
    """OpenAPI document of the simd API (exported to devices/simd/openapi.json)."""
    from netsim_simd.api import create_app

    return create_app(None).openapi()  # type: ignore[arg-type]


# ---------------------------------------------------------------------------------------------- CLI
def _write_or_check(out: Path, text: str, check: bool, hint: str) -> int:
    if check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"ERROR: {out} is out of date - run `{hint}`", file=sys.stderr)
            return 1
        print(f"OK: {out} is up to date")
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


def _cmd_openapi(args: argparse.Namespace) -> int:
    text = json.dumps(openapi_document(), indent=2) + "\n"
    return _write_or_check(Path(args.out), text, args.check, "make devices-openapi")


def _cmd_datafile(args: argparse.Namespace) -> int:
    from netsim_common.oids import load_oids
    from netsim_simd.mibview import MibView
    from netsim_simd.snmpdb import write_datafile

    community = args.community or lab_constants().snmp_community
    path = write_datafile(Path(args.dir), community, MibView(load_oids()).anchor())
    print(f"snmpsim data file {path}: {path.read_text(encoding='ascii').strip()}")
    return 0


def _cmd_render(args: argparse.Namespace) -> int:
    return _write_or_check(Path(args.out), render_compose(), args.check, "make devices-compose")


def _json(url: str) -> Any:
    with urllib.request.urlopen(url, timeout=2) as resp:
        return json.loads(resp.read())


def _cmd_wait(args: argparse.Namespace) -> int:
    lab = lab_constants()
    hosts = args.hosts or list(lab.devices)
    start = time.monotonic()
    pending = dict.fromkeys(hosts, "no answer")
    while time.monotonic() - start < args.timeout:
        for host in list(pending):
            try:
                health = _json(f"{lab.devices[host].simd_url}/health")
                state = _json(f"{lab.devices[host].simd_url}/state")
            except OSError as exc:
                pending[host] = str(exc)
                continue
            down = [
                f"{p['service_id']}:{p['role']}={p['oper']}/{p['reason']}"
                for p in state["pseudowires"]
                if p["oper"] != "up"
            ]
            if health.get("status") != "ok":
                pending[host] = f"health {health.get('status')}"
            elif down:
                pending[host] = "down: " + ", ".join(down)
            else:
                del pending[host]
                print(f"{host}: ready, {len(state['pseudowires'])} PW(s) up ({time.monotonic() - start:.1f}s)")
        if not pending:
            print(f"all {len(hosts)} device(s) ready in {time.monotonic() - start:.1f}s")
            return 0
        time.sleep(0.5)
    for host, why in sorted(pending.items()):
        print(f"{host}: NOT ready: {why}", file=sys.stderr)
    return 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    render = sub.add_parser("render-compose", help="(re)write devices/compose.yaml from the topology")
    render.add_argument("--check", action="store_true", help="verify only")
    render.add_argument("--out", default=str(repo_root() / "devices" / "compose.yaml"))
    render.set_defaults(func=_cmd_render)
    datafile = sub.add_parser("snmp-datafile", help="write the snmpsim data file <community>.snmprec")
    datafile.add_argument("--dir", required=True)
    datafile.add_argument("--community", default="", help="default: topology snmp.community")
    datafile.set_defaults(func=_cmd_datafile)
    api = sub.add_parser("openapi", help="(re)write devices/simd/openapi.json")
    api.add_argument("--check", action="store_true", help="verify only")
    api.add_argument("--out", default=str(repo_root() / "devices" / "simd" / "openapi.json"))
    api.set_defaults(func=_cmd_openapi)
    wait = sub.add_parser("wait", help="wait until devices are healthy and all their PWs are up")
    wait.add_argument("hosts", nargs="*")
    wait.add_argument("--timeout", type=float, default=90.0)
    wait.set_defaults(func=_cmd_wait)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
