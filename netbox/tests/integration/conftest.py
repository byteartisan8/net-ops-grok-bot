"""Throwaway NetBox stack for the NetBox integration tests (owner: 03-netbox).

Rendered from ``netbox/compose.yaml`` (same images, env and healthchecks) onto a private network with an
ephemeral host port, compose project ``netsim-nb-it``, so it never touches the lab's NetBox:

    make netbox-test-integration          # = uv run pytest netbox/tests/integration -m integration

First start applies every migration (~4 min). ``NETBOX_IT_KEEP=1`` leaves the stack running and reuses it next
time (state in ``build/netbox-it/``). ``NETBOX_IT_USE_LAB=1`` runs against the lab's NetBox instead (``.env`` URL
and tokens); the tests revert what they change, but the lab's webhooks fire while they run.
"""

from __future__ import annotations

import os
import secrets
import subprocess
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

import pytest
import yaml
from netsim_netbox.bootstrap import bootstrap
from netsim_netbox.client import NetBoxClient
from netsim_netbox.envfile import read_env_file
from netsim_netbox.settings import get_setting, load_settings

from netsim_common.paths import repo_root

PROJECT = "netsim-nb-it"
STATE = repo_root() / "build" / "netbox-it"
TEST_WEBHOOK_SECRET = "it-webhook-secret"


@dataclass
class NetBox:
    url: str
    token_rw: str
    token_ro: str
    webhook_secret: str
    env: dict[str, str]

    def rw(self) -> NetBoxClient:
        return NetBoxClient(self.url, self.token_rw)

    def ro(self) -> NetBoxClient:
        return NetBoxClient(self.url, self.token_ro)

    def cli_env(self) -> dict[str, str]:
        """Environment for the CLIs (the environment wins over the repo's .env)."""
        return {
            **os.environ,
            "NETBOX_URL": self.url,
            "NETBOX_PUBLIC_URL": self.url,
            "NETBOX_TOKEN_RW": self.token_rw,
            "NETBOX_TOKEN_RO": self.token_ro,
            "NETBOX_WEBHOOK_SECRET": self.webhook_secret,
        }


def _compose(*args: str, timeout: float = 900, check: bool = True) -> subprocess.CompletedProcess[str]:
    cmd = ["docker", "compose", "-p", PROJECT, "-f", str(STATE / "compose.yaml"), "--env-file", str(STATE / "env")]
    proc = subprocess.run([*cmd, *args], capture_output=True, text=True, timeout=timeout)
    if check and proc.returncode != 0:
        raise RuntimeError(f"docker compose {' '.join(args)} failed:\n{proc.stdout}\n{proc.stderr}")
    return proc


def render_test_compose() -> str:
    """netbox/compose.yaml without labnet, static IPs, container names or fixed host ports."""
    fragment = yaml.safe_load((repo_root() / "netbox" / "compose.yaml").read_text(encoding="utf-8"))
    for service in fragment["services"].values():
        service.pop("container_name", None)
        nets = service["networks"]
        if isinstance(nets, dict) and "labnet" in nets:
            nets.pop("labnet")
            nets["it-net"] = {}
        if "ports" in service:
            service["ports"] = ["127.0.0.1::8080/tcp"]
    fragment["networks"] = {"it-net": {}, "netbox-internal": {"internal": True}}
    return "# GENERATED by netbox/tests/integration/conftest.py from netbox/compose.yaml\n" + yaml.safe_dump(
        fragment, sort_keys=False
    )


def _test_env() -> dict[str, str]:
    path = STATE / "env"
    if path.exists():  # reused stack: same secrets
        return read_env_file(path)
    token = lambda n: secrets.token_urlsafe(n)[:n]  # noqa: E731
    return {
        "NETBOX_DB_NAME": "netbox",
        "NETBOX_DB_USER": "netbox",
        "NETBOX_DB_PASSWORD": token(24),
        "NETBOX_REDIS_PASSWORD": token(24),
        "NETBOX_REDIS_CACHE_PASSWORD": token(24),
        "NETBOX_SECRET_KEY": token(64),
        "NETBOX_API_TOKEN_PEPPER": token(64),
        "NETBOX_SUPERUSER_NAME": "admin",
        "NETBOX_SUPERUSER_EMAIL": "admin@example.com",
        "NETBOX_SUPERUSER_PASSWORD": token(20) + "Aa1",
    }


def _running() -> bool:
    proc = _compose("ps", "--format", "{{.Service}} {{.Health}}", check=False, timeout=60)
    states = dict(line.split(" ", 1) for line in proc.stdout.splitlines() if " " in line)
    return states.get("netbox") == "healthy"


@pytest.fixture(scope="session")
def netbox() -> Iterator[NetBox]:
    if os.environ.get("NETBOX_IT_USE_LAB") == "1":
        settings = load_settings()
        if not settings.token_rw or not settings.token_ro:
            pytest.skip("NETBOX_IT_USE_LAB=1 needs the lab's tokens in .env (make netbox-up)")
        secret = get_setting("NETBOX_WEBHOOK_SECRET") or ""
        yield NetBox(settings.url, settings.token_rw, settings.token_ro, secret, {})
        return
    if subprocess.run(["docker", "info"], capture_output=True).returncode != 0:
        pytest.skip("needs a Docker daemon")
    keep = os.environ.get("NETBOX_IT_KEEP") == "1"
    STATE.mkdir(parents=True, exist_ok=True)
    env = _test_env()
    (STATE / "env").write_text("".join(f"{k}={v}\n" for k, v in env.items()), encoding="utf-8")
    (STATE / "compose.yaml").write_text(render_test_compose(), encoding="utf-8")
    if not (keep and _running()):
        _compose("down", "--volumes", "--remove-orphans", check=False)
        _compose("up", "-d", "--wait", "--wait-timeout", "600")
    port = _compose("port", "netbox", "8080").stdout.strip().rsplit(":", 1)[1]
    url = f"http://127.0.0.1:{port}"
    tokens_file = STATE / "tokens.env"
    tokens_file.touch(mode=0o600, exist_ok=True)
    result = bootstrap(
        url,
        env["NETBOX_SUPERUSER_NAME"],
        env["NETBOX_SUPERUSER_PASSWORD"],
        read_env_file(tokens_file),
        env_file=tokens_file,
        quiet=True,
    )
    rw, ro = (t.token for t in result.tokens)
    try:
        yield NetBox(url, rw, ro, TEST_WEBHOOK_SECRET, env)
    finally:
        if not keep:
            _compose("down", "--volumes", "--remove-orphans", check=False)
            for name in ("env", "tokens.env", "compose.yaml"):
                (STATE / name).unlink(missing_ok=True)


@pytest.fixture(scope="session")
def repo() -> Path:
    return repo_root()
