"""``netbox-bootstrap``: wait for NetBox, then provision the lab's API tokens (contract section 11).

How tokens work in the pinned NetBox (4.7.3, verified on a running instance):

* v2 tokens (the default since 4.5) are ``nbt_<12-char key>.<40-char secret>``, sent as
  ``Authorization: Bearer nbt_<key>.<secret>``. NetBox stores only an HMAC-SHA256 digest made with the pepper
  ``API_TOKEN_PEPPERS[1]`` (``.env``: ``NETBOX_API_TOKEN_PEPPER``, >= 50 characters), so the plaintext is returned
  exactly once, in the response that creates the token. The key is not secret and identifies the token.
* Since 4.7 the plaintext is always generated by NetBox: the REST API ignores client-supplied values, so the
  bootstrap asks NetBox for tokens and writes what it gets into ``.env``.

Tokens:

* ``NETBOX_TOKEN_RW``: the superuser's token (the superuser is created from ``.env`` by the image on first start),
  obtained with ``POST /api/users/tokens/provision/`` (username + password), write enabled;
* ``NETBOX_TOKEN_RO``: token of the dedicated user ``netsim-bot`` (group ``netsim-readonly``, whose object permission
  ``netsim-readonly`` grants only ``view`` on every public object type outside the ``users`` app, except webhooks,
  which hold the HMAC secret), created with ``POST /api/users/tokens/`` and ``write_enabled=false``: read-only both
  by permission and by token.

A token already in ``.env`` is kept when it still authenticates as the right user with the right write ability;
otherwise (unset, database recreated, wrong user, legacy v1 value) it is replaced. Tokens that an earlier bootstrap
created and that ``.env`` no longer holds are deleted. A second run changes nothing.
"""

from __future__ import annotations

import argparse
import secrets
import string
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import httpx

from netsim_netbox.client import TOKEN_PREFIX, NetBoxClient, NetBoxError, describe_token, token_key
from netsim_netbox.envfile import default_env_file, read_env_file, update_env_file
from netsim_netbox.settings import TOKEN_RO, TOKEN_RW, load_settings

RO_USER = "netsim-bot"
RO_GROUP = "netsim-readonly"
RO_PERMISSION = "netsim-readonly"
#: Apps whose object types the read-only permission does not cover (accounts, tokens, permissions).
RO_EXCLUDED_APPS = frozenset({"users"})
#: Object types holding secrets (the webhook's HMAC secret and headers).
RO_EXCLUDED_TYPES = frozenset({"extras.webhook"})
RW_DESCRIPTION = "netsim NETBOX_TOKEN_RW (seeding, remediation), managed by netbox-bootstrap"
RO_DESCRIPTION = "netsim NETBOX_TOKEN_RO (bot: intent, BSM spec, queries), managed by netbox-bootstrap"


class BootstrapError(RuntimeError):
    pass


@dataclass
class TokenResult:
    name: str
    token: str
    user: str
    write_enabled: bool
    action: str  # "kept" | "created"
    replaced: str | None = None  # why the previous value was not kept


@dataclass
class BootstrapResult:
    version: str
    tokens: list[TokenResult] = field(default_factory=list)
    readonly_object_types: int = 0
    deleted_tokens: int = 0
    written: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------------------------- waiting
def wait_ready(url: str, timeout: float = 420.0, *, interval: float = 2.0, quiet: bool = False) -> float:
    """Wait until NetBox serves its login page (what the container healthcheck probes); returns seconds waited."""
    start = time.monotonic()
    last = ""
    next_note = start + 15
    while True:
        try:
            resp = httpx.get(f"{url.rstrip('/')}/login/", timeout=5)
            if resp.status_code == 200:
                return time.monotonic() - start
            last = f"HTTP {resp.status_code}"
        except httpx.HTTPError as exc:
            last = type(exc).__name__
        now = time.monotonic()
        if now - start > timeout:
            raise BootstrapError(f"NetBox at {url} not ready after {timeout:.0f}s ({last}); see `make netbox-logs`")
        if not quiet and now >= next_note:
            print(f"netbox-bootstrap: waiting for NetBox at {url} ({now - start:.0f}s, {last})", file=sys.stderr)
            next_note = now + 15
        time.sleep(interval)


# --------------------------------------------------------------------------------------------- helpers
def _password() -> str:
    """Random password meeting NetBox's validators (>= 12 chars, a digit, an upper- and a lower-case letter)."""
    alphabet = string.ascii_letters + string.digits
    body = "".join(secrets.choice(alphabet) for _ in range(32))
    return (
        body
        + secrets.choice(string.ascii_uppercase)
        + secrets.choice(string.ascii_lowercase)
        + secrets.choice(string.digits)
    )


def _whoami(url: str, token: str) -> dict[str, Any] | None:
    """The user a token authenticates as (``None`` when NetBox rejects it)."""
    with NetBoxClient(url, token) as client:
        try:
            return client.get("authentication-check")
        except NetBoxError as exc:
            if exc.status in (401, 403):
                return None
            raise


def _token_record(admin: NetBoxClient, token: str) -> dict[str, Any] | None:
    key = token_key(token)
    if key is None:
        return None
    rows = admin.list("users/tokens", key=key)
    return rows[0] if rows else None


def _full_token(created: dict[str, Any]) -> str:
    """``nbt_<key>.<secret>`` from a token creation response (the secret is only in that response)."""
    secret, key = created.get("token"), created.get("key")
    if not secret or not key or int(created.get("version", 2)) != 2:
        raise BootstrapError(f"unexpected token creation response (version {created.get('version')})")
    return f"{TOKEN_PREFIX}{key}.{secret}"


def _one(client: NetBoxClient, endpoint: str, **params: Any) -> dict[str, Any] | None:
    rows = client.list(endpoint, **params)
    if len(rows) > 1:
        raise BootstrapError(f"{endpoint}: more than one object matches {params}")
    return rows[0] if rows else None


def _ids(objs: list[Any]) -> list[int]:
    return sorted(o["id"] if isinstance(o, dict) else int(o) for o in objs)


# --------------------------------------------------------------------------------------------- RW token
def ensure_rw_token(url: str, current: str | None, username: str, password: str) -> TokenResult:
    replaced = None
    if current:
        if token_key(current) is None:
            replaced = "not a v2 token"
        elif (user := _whoami(url, current)) is None:
            replaced = "rejected by NetBox (database recreated?)"
        elif user["username"] != username:
            replaced = f"belongs to {user['username']!r}, not the superuser {username!r}"
        else:
            with NetBoxClient(url, current) as admin:
                record = _token_record(admin, current)
            if record and record["enabled"] and record["write_enabled"]:
                return TokenResult(TOKEN_RW, current, username, True, "kept")
            replaced = "not write enabled"
    if not password:
        raise BootstrapError("NETBOX_SUPERUSER_PASSWORD is not set (run `make env`)")
    with NetBoxClient(url) as anonymous:
        try:
            created = anonymous.create(
                "users/tokens/provision",
                {"username": username, "password": password, "write_enabled": True, "description": RW_DESCRIPTION},
            )
        except NetBoxError as exc:
            raise BootstrapError(
                f"cannot provision a token for {username!r}: {exc.detail} (does .env match the superuser that "
                "NetBox created on its first start?)"
            ) from exc
    return TokenResult(TOKEN_RW, _full_token(created), username, True, "created", replaced)


# --------------------------------------------------------------------------------------------- RO user + token
def readonly_object_types(admin: NetBoxClient) -> list[str]:
    rows = admin.list("core/object-types", public=True)
    names = (f"{o['app_label']}.{o['model']}" for o in rows if o["app_label"] not in RO_EXCLUDED_APPS)
    return sorted(n for n in names if n not in RO_EXCLUDED_TYPES)


def ensure_readonly_user(admin: NetBoxClient) -> tuple[int, int]:
    """Group, view-only permission and user ``netsim-bot``; returns (user id, number of object types)."""
    group = _one(admin, "users/groups", name=RO_GROUP)
    if group is None:
        group = admin.create(
            "users/groups", {"name": RO_GROUP, "description": "Read-only access to the lab data (netsim bot)"}
        )
    object_types = readonly_object_types(admin)
    wanted = {
        "name": RO_PERMISSION,
        "description": "View every lab object (no add/change/delete); managed by netbox-bootstrap",
        "enabled": True,
        "actions": ["view"],
        "object_types": object_types,
        "groups": [group["id"]],
    }
    perm = _one(admin, "users/permissions", name=RO_PERMISSION)
    if perm is None:
        admin.create("users/permissions", wanted)
    else:
        have = {
            "description": perm["description"],
            "enabled": perm["enabled"],
            "actions": sorted(perm["actions"]),
            "object_types": sorted(perm["object_types"]),
            "groups": _ids(perm["groups"]),
        }
        changes = {k: v for k, v in wanted.items() if k != "name" and have.get(k) != v}
        if changes:
            admin.update("users/permissions", perm["id"], changes)
    user = _one(admin, "users/users", username=RO_USER)
    if user is None:
        user = admin.create(
            "users/users",
            {
                "username": RO_USER,
                # Token-only account: the password is random and not kept anywhere.
                "password": _password(),
                "first_name": "netsim",
                "last_name": "bot (read-only)",
                "is_active": True,
                "groups": [group["id"]],
            },
        )
    elif not user["is_active"] or group["id"] not in _ids(user["groups"]):
        admin.update(
            "users/users", user["id"], {"is_active": True, "groups": sorted({*_ids(user["groups"]), group["id"]})}
        )
    return user["id"], len(object_types)


def ensure_ro_token(url: str, admin: NetBoxClient, current: str | None, user_id: int) -> TokenResult:
    replaced = None
    if current:
        record = _token_record(admin, current) if token_key(current) else None
        if token_key(current) is None:
            replaced = "not a v2 token"
        elif record is None:
            replaced = "unknown to NetBox (database recreated?)"
        elif record["user"]["id"] != user_id:
            replaced = f"belongs to {record['user'].get('username')!r}, not {RO_USER!r}"
        elif record["write_enabled"] or not record["enabled"]:
            replaced = "write enabled or disabled"
        elif _whoami(url, current) is None:
            replaced = "rejected by NetBox"
        else:
            return TokenResult(TOKEN_RO, current, RO_USER, False, "kept")
    created = admin.create("users/tokens", {"user": user_id, "write_enabled": False, "description": RO_DESCRIPTION})
    return TokenResult(TOKEN_RO, _full_token(created), RO_USER, False, "created", replaced)


def delete_stale_tokens(admin: NetBoxClient, keep: list[str]) -> int:
    """Delete tokens created by earlier bootstraps (same description) that are not in ``keep``."""
    keys = {token_key(t) for t in keep}
    stale = [
        t["id"]
        for t in admin.list("users/tokens")
        if t["description"] in (RW_DESCRIPTION, RO_DESCRIPTION) and t["key"] not in keys
    ]
    if stale:
        admin.bulk_delete("users/tokens", stale)
    return len(stale)


def check_readonly(url: str, token: str) -> None:
    """The RO token can read but cannot write (an empty POST is refused before any validation)."""
    with NetBoxClient(url, token) as client:
        client.list("dcim/devices", limit=1)
        try:
            client.create("extras/tags", {})
        except NetBoxError as exc:
            if exc.status == 403:
                return
            raise BootstrapError(f"{TOKEN_RO}: expected 403 on write, got HTTP {exc.status}") from exc
        raise BootstrapError(f"{TOKEN_RO}: a write request was accepted")


# --------------------------------------------------------------------------------------------- main flow
def bootstrap(
    url: str,
    username: str,
    password: str,
    env: dict[str, str],
    *,
    env_file: Path | None = None,
    timeout: float = 420.0,
    quiet: bool = False,
) -> BootstrapResult:
    """Wait for NetBox, make sure both tokens are valid, write new ones to ``env_file``."""
    wait_ready(url, timeout, quiet=quiet)
    written: list[str] = []

    def save(token: TokenResult) -> None:
        # Right away: a new plaintext exists only in memory until it is in the file.
        if env_file is not None:
            written.extend(update_env_file(env_file, {token.name: token.token}))

    rw = ensure_rw_token(url, env.get(TOKEN_RW), username, password)
    save(rw)
    with NetBoxClient(url, rw.token) as admin:
        version = admin.status()["netbox-version"]
        user_id, n_types = ensure_readonly_user(admin)
        ro = ensure_ro_token(url, admin, env.get(TOKEN_RO), user_id)
        save(ro)
        check_readonly(url, ro.token)
        result = BootstrapResult(version=version, tokens=[rw, ro], readonly_object_types=n_types, written=written)
        result.deleted_tokens = delete_stale_tokens(admin, [rw.token, ro.token])
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="netbox-bootstrap", description=__doc__.split("\n\n")[0])
    parser.add_argument("--env-file", type=Path, help="env file to read and update (default: the repo's .env)")
    parser.add_argument("--timeout", type=float, default=420.0, help="seconds to wait for NetBox (default 420)")
    args = parser.parse_args(argv)

    env_file = args.env_file or default_env_file()
    if env_file is None or not env_file.is_file():
        print("netbox-bootstrap: error: no .env file (run `make env`)", file=sys.stderr)
        return 2
    # Tokens and credentials come from the file this command manages; NETBOX_URL may also come from the environment.
    env = read_env_file(env_file)
    settings = load_settings(env_file=env_file)
    try:
        result = bootstrap(
            settings.url,
            env.get("NETBOX_SUPERUSER_NAME", "admin"),
            env.get("NETBOX_SUPERUSER_PASSWORD", ""),
            env,
            env_file=env_file,
            timeout=args.timeout,
        )
    except (BootstrapError, NetBoxError) as exc:
        print(f"netbox-bootstrap: error: {exc}", file=sys.stderr)
        return 1
    print(f"netbox-bootstrap: NetBox {result.version} at {settings.url}")
    for t in result.tokens:
        mode = "write enabled" if t.write_enabled else f"read-only ({result.readonly_object_types} object types)"
        note = f"{t.action}" + (f", previous value {t.replaced}" if t.replaced else "")
        written = " -> .env" if t.name in result.written else ""
        print(f"  {t.name:<16} {describe_token(t.token):<22} user {t.user:<11} {mode:<34} {note}{written}")
    if result.deleted_tokens:
        print(f"  deleted {result.deleted_tokens} stale token(s) from earlier bootstraps")
    return 0


if __name__ == "__main__":
    sys.exit(main())
